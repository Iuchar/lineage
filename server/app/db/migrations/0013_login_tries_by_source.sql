-- Счёт промахов — по имени и адресу вместе. По одному имени он давал прохожему способ держать
-- редактора за дверью: набирай чепуху под его именем, и верный пароль не пускает.
-- Прежний счёт не переносится: он живёт минуты и нужен только пока идёт подбор.

DROP TABLE login_tries;

CREATE TABLE login_tries (
    name     TEXT NOT NULL,     -- имя как его набрали, без оглядки на то, есть ли такой редактор
    source   TEXT NOT NULL,     -- адрес, с которого пришла попытка; пусто, если он неизвестен
    misses   INTEGER NOT NULL DEFAULT 0,
    last_at  TEXT NOT NULL,     -- когда была последняя неудача
    open_at  TEXT,              -- раньше этого момента попытки не принимаются; NULL — принимаются
    PRIMARY KEY (name, source)
);

-- по этому указателю убираются давние промахи: счёт ведётся и по выдуманным именам,
-- и без уборки таблицу можно было бы набивать без конца
CREATE INDEX login_tries_last ON login_tries(last_at);
