-- Отпор подбору пароля. Счёт неудач подряд ведётся по набранному имени — в том числе по тому,
-- которого в заводе нет: иначе отказ «подождите» сам говорил бы, какое имя заведено.
-- Удачный вход счёт обнуляет, так что обычные опечатки хозяина ничего не копят.

CREATE TABLE login_tries (
    name     TEXT PRIMARY KEY,  -- имя как его набрали, без оглядки на то, есть ли такой редактор
    misses   INTEGER NOT NULL DEFAULT 0,
    last_at  TEXT NOT NULL,     -- когда была последняя неудача
    open_at  TEXT               -- раньше этого момента попытки не принимаются; NULL — принимаются
);
